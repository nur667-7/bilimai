export function getOptionFeedback(
  topic: TopicId,
  questionIndex: number,
  optionIndex: number,
  lang: Language
): string {
  const lesson = lessons[lang].find((l) => l.id === topic) ?? lessons.ru[0];
  const question = lesson.questions[questionIndex];
  if (!question) return "";
  if (optionIndex === question.correct) {
    return question.why;
  }
  const specific = wrongOptionDiagnostics[lang]?.[topic]?.[questionIndex]?.[optionIndex];
  if (specific) return specific;
  return question.why;
}

